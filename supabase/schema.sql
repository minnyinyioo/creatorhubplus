create or replace function public.current_creatorhubplus_user_id()
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select id from public.users where "authUserId" = auth.uid() limit 1;
$$;

create or replace function public.current_creatorhubplus_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.users
    where "authUserId" = auth.uid() and role = 'admin'
  );
$$;


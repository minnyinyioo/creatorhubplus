-- CreatorHubPlus Supabase target schema.
-- This file is intentionally separate from Drizzle's current MySQL schema until the
-- one-time migration is verified. It preserves legacy integer IDs for safe mapping.

create table if not exists public.users (
  id integer generated by default as identity primary key,
  "openId" text not null unique,
  name text,
  email varchar(320),
  "loginMethod" text,
  role text not null default 'user' check (role in ('user', 'admin')),
  "authUserId" uuid unique references auth.users(id) on delete set null,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  "lastSignedIn" timestamptz not null default now()
);

create table if not exists public.payment_service_catalog (
  id integer generated by default as identity primary key,
  "serviceKey" text not null unique,
  "serviceLabel" text not null,
  "priceMmk" integer,
  "priceLabel" text not null default 'Quote required',
  "isActive" boolean not null default true,
  "updatedByUserId" integer references public.users(id) on delete set null,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists public.payment_requests (
  id integer generated by default as identity primary key,
  "userId" integer not null references public.users(id) on delete cascade,
  "requestCode" text not null unique,
  "orderNumber" text not null unique,
  "paymentMethod" text not null,
  "serviceKey" text,
  "serviceLabel" text,
  "payerName" text not null,
  "accountHint" text,
  "amountMmk" integer not null,
  "quotedAmountMmk" integer,
  "paymentReference" text,
  "receiptStorageKey" text not null,
  "receiptUrl" text not null,
  "receiptName" text not null,
  "receiptContentType" text not null,
  status text not null default 'pending_review' check (status in ('pending_review', 'clarification_requested', 'verified', 'rejected')),
  "reviewNote" text,
  "reviewedByUserId" integer references public.users(id) on delete set null,
  "reviewedAt" timestamptz,
  "createdAt" timestamptz not null default now()
);

create table if not exists public.payment_notifications (
  id integer generated by default as identity primary key,
  "userId" integer not null references public.users(id) on delete cascade,
  "paymentRequestId" integer references public.payment_requests(id) on delete cascade,
  kind text not null check (kind in ('submitted', 'clarification_requested', 'verified', 'rejected')),
  title text not null,
  message text not null,
  "readAt" timestamptz,
  "createdAt" timestamptz not null default now()
);

create table if not exists public.invoices (
  id integer generated by default as identity primary key,
  "paymentRequestId" integer not null unique references public.payment_requests(id) on delete cascade,
  "userId" integer not null references public.users(id) on delete cascade,

  "orderNumber" text not null,
  "serviceLabel" text not null,
  "customerName" text not null,
  "customerEmail" varchar(320),
  "paymentMethod" text not null,
  "amountMmk" integer not null,
  currency varchar(3) not null default 'MMK',
  status text not null default 'issued' check (status in ('issued', 'voided')),
  "pdfStorageKey" text not null,
  "pdfUrl" text not null,
  "complianceNote" text not null default 'This electronic invoice confirms a payment request marked as verified by CreatorHubPlus. Keep it for your records.',
  "issuedAt" timestamptz not null default now(),
  "createdAt" timestamptz not null default now()
);

